/** Map every released priority to its bilingual label. */
export const priorityMessageKey: Record<Priority, OrdersMessageKey> = {
  routine: 'priorityRoutine',
  urgent: 'priorityUrgent',
  stat: 'priorityStat',
};

/** Look up one orders label for the active locale. */
export function ordersText(locale: Locale, key: OrdersMessageKey): string {
  return ordersMessages[locale][key];
}

/** Wire action names emitted by the XCH-03 history ledger. */
const timelineActionKey: Readonly<Record<string, OrdersMessageKey | undefined>> = {
  accept: 'actionAccept',
  reject: 'actionReject',
  clarify: 'actionClarify',
  propose_change: 'actionProposeChange',
  change_response: 'actionChangeResponse',
  request_cancellation: 'actionRequestCancellation',
  cancellation_response: 'actionCancellationResponse',
  revoke: 'actionRevoke',
};

/**
 * Render a wire state in the active language. History is an external ledger, so
 * an unknown token is shown verbatim rather than crashing the timeline.
 */
export function orderStateLabel(locale: Locale, wire: string): string {
  const key = (orderStateKey as Readonly<Record<string, OrdersMessageKey | undefined>>)[wire];
  return key === undefined ? wire : ordersText(locale, key);
}

/** Render a wire action in the active language, with a safe verbatim fallback. */
export function timelineActionLabel(locale: Locale, action: string): string {
  const key = timelineActionKey[action];
  return key === undefined ? action : ordersText(locale, key);
}
