/** Map each access state to its bilingual label key. */
export const accessStateMessageKey: Record<AccessState, AdminMessageKey> = {
  permitted: 'accessPermitted',
  denied: 'accessDenied',
  concealed: 'accessConcealed',
};

/** Map each staff event kind to its bilingual label key. */
export const staffEventMessageKey: Record<StaffHistoryEvent['kind'], AdminMessageKey> = {
  invited: 'eventInvited',
  role_granted: 'eventRoleGranted',
  deactivated: 'eventDeactivated',
};

/** Map each audit outcome to its bilingual label key. */
export const outcomeMessageKey: Record<AuditOutcome, AdminMessageKey> = {
  SUCCESS: 'outcomeSuccess',
  DENIED: 'outcomeDenied',
};

/** Look up one administration label for the active locale. */
export function adminText(locale: Locale, key: AdminMessageKey): string {
  return adminMessages[locale][key];
}

/** Build the localized, revision-specific announcement for a local proposal. */
export function proposalAnnouncement(locale: Locale, facilityCode: string, version: number): string {
  return adminText(locale, 'proposalAnnounced')
    .replace('{facility}', facilityCode)
    .replace('{version}', String(version));
}
