/** State-to-label lookup; keep the record private behind a total function. */
const stateMessageKeys: Record<PrescriptionState, PharmacyMessageKey> = {
  draft: 'stateDraft',
  attested: 'stateAttested',
  submitted: 'stateSubmitted',
  ambiguous: 'stateAmbiguous',
  delivery_confirmed: 'stateDeliveryConfirmed',
  accepted: 'stateAccepted',
  rejected: 'stateRejected',
  clarification: 'stateClarification',
  dispensed: 'stateDispensed',
  printed: 'statePrinted',
  cancelled: 'stateCancelled',
};

/** Filter-to-label lookup; keep the record private behind a total function. */
const filterMessageKeys: Record<StatusFilter, PharmacyMessageKey> = {
  all: 'filterAll',
  submitted: 'filterSubmitted',
  delivery_confirmed: 'filterDeliveryConfirmed',
  accepted: 'filterAccepted',
  rejected: 'filterRejected',
  clarification: 'filterClarification',
  dispensed: 'filterDispensed',
};

/** Map a prescription state to its bilingual label key. */
export function stateMessageKey(state: PrescriptionState): PharmacyMessageKey {
  return stateMessageKeys[state];
}

/** Map an inbox filter to its bilingual label key. */
export function filterMessageKey(filter: StatusFilter): PharmacyMessageKey {
  return filterMessageKeys[filter];
}

/** Look up one pharmacy label for the active locale. */
export function pharmacyText(locale: Locale, key: PharmacyMessageKey): string {
  return pharmacyMessages[locale][key];
}
