/** Map every transmission event kind to its bilingual label key. */
export const prescriptionEventMessageKey: Record<
  PrescriptionEventKind,
  PrescriptionMessageKey
> = {
  submitted: 'eventSubmitted',
  delivery_confirmed: 'eventDeliveryConfirmed',
  accepted: 'eventAccepted',
  rejected: 'eventRejected',
  dispensed: 'eventDispensed',
  clarification: 'eventClarification',
  renewal: 'eventRenewal',
  cancelled: 'eventCancelled',
};

/** Look up one prescription label for the active locale. */
export function prescriptionText(locale: Locale, key: PrescriptionMessageKey): string {
  return prescriptionMessages[locale][key];
}
