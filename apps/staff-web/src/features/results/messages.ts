/** Look up one result label for the active locale. */
export function resultText(locale: Locale, key: ResultMessageKey): string {
  return resultMessages[locale][key];
}

/**
 * Fill named `{placeholder}` slots without interpreting user text. Unknown
 * placeholders remain visible so a missing value is never rendered as a blank.
 */
export function resultMessage(
  locale: Locale,
  key: ResultMessageKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return resultText(locale, key).replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}

