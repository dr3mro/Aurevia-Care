/** Look up one policy label for the active locale. */
export function policyText(locale: Locale, key: PolicyMessageKey): string {
  return policyMessages[locale][key];
}

/**
 * Fill named placeholders in a policy label. An unknown placeholder is left
 * intact so a missing value is visible rather than silently blank.
 */
export function policyMessage(
  locale: Locale,
  key: PolicyMessageKey,
  values: Readonly<Record<string, string>> = {},
): string {
  return policyText(locale, key).replace(/\{(\w+)\}/g, (whole, name: string) => values[name] ?? whole);
}
