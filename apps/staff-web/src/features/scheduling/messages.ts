/** Look up one scheduling label for the active locale. */
export function schedulingText(locale: Locale, key: SchedulingMessageKey): string {
  return schedulingMessages[locale][key];
}

/**
 * Interpolate one value into a scheduling label. The placeholder is replaced
 * literally so a synthetic identifier never becomes a format string; values
 * are kept out of the dictionary so both languages share the same keys.
 */
export function schedulingTextWithValue(
  locale: Locale,
  key: SchedulingMessageKey,
  value: string | number,
): string {
  return schedulingText(locale, key).replace('{value}', String(value));
}
