/** Map each order state to its bilingual badge label key. */
export const stateMessageKey: Record<ImagingOrderState, RadiologyMessageKey> = {
  received: 'stateReceived',
  scheduled: 'stateScheduled',
  'study-linked': 'stateStudyLinked',
  interpreted: 'stateInterpreted',
  addended: 'stateAddended',
};

/** Map each urgency to its bilingual label key. */
export const urgencyMessageKey: Record<Urgency, RadiologyMessageKey> = {
  routine: 'urgencyRoutine',
  urgent: 'urgencyUrgent',
  stat: 'urgencyStat',
};

/** Look up one radiography label for the active locale. */
export function radiologyText(locale: Locale, key: RadiologyMessageKey): string {
  return radiologyMessages[locale][key];
}
