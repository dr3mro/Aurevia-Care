/** Map a referral state to its bilingual label key. */
export const referralStateMessageKey: Record<ReferralState, TherapyMessageKey> = {
  pending: 'statePending',
  accepted: 'stateAccepted',
  closed: 'stateClosed',
};

/** Map an episode state to its bilingual label key. */
export const episodeStateMessageKey: Record<EpisodeState, TherapyMessageKey> = {
  active: 'stateActive',
  discharged: 'stateDischarged',
};

/** Map a goal state to its bilingual label key. */
export const goalStateMessageKey: Record<GoalState, TherapyMessageKey> = {
  active: 'goalActive',
  met: 'goalMet',
  discontinued: 'goalDiscontinued',
};

/** Map a note state to its bilingual label key. */
export const noteStateMessageKey: Record<NoteState, TherapyMessageKey> = {
  draft: 'stateDraft',
  signed: 'stateSigned',
};

/** Look up one therapy label for the active locale. */
export function therapyText(locale: Locale, key: TherapyMessageKey): string {
  return therapyMessages[locale][key];
}
