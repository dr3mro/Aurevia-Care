/** Look up one messages label for the active locale. */
export function messagesText(locale: Locale, key: MessagesMessageKey): string {
  return messagesTexts[locale][key];
}

/**
 * Fill named placeholders in a messages label. Unknown placeholders stay
 * visible so a missing value cannot silently disappear from a clinical screen.
 */
export function messagesMessage(
  locale: Locale,
  key: MessagesMessageKey,
  values: Readonly<Record<string, string>> = {},
): string {
  return messagesText(locale, key).replace(/\{(\w+)\}/g, (whole, name: string) => values[name] ?? whole);
}
