/** Map each coded-entry verification state to its bilingual badge label. */
export const verificationMessageKey: Record<ChartVerification, ChartMessageKey> = {
  verified: 'verificationVerified',
  unverified: 'verificationUnverified',
  unknown: 'verificationUnknown',
  none: 'verificationNone',
};

/** Look up one chart label for the active locale. */
export function chartText(locale: Locale, key: ChartMessageKey): string {
  return chartMessages[locale][key];
}
