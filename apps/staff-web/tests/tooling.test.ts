import { readFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

const here = dirname(fileURLToPath(import.meta.url));
const moduleRoot = resolve(here, '..');
const read = (path: string) => readFileSync(resolve(moduleRoot, path), 'utf8');

describe('module delivery hooks', () => {
  it('wires generated-client drift, types, lint and 100% coverage into check.sh', () => {
    const check = read('check.sh');
    expect(check).toContain('npm run gen:api:check');
    expect(check).toContain('npm run typecheck');
    expect(check).toContain('npm run lint');
    expect(check).toContain('npm run test:coverage');
  });

  it('builds TypeDoc into the supplied absolute directory and writes index.html', () => {
    const docs = read('docs.sh');
    expect(docs).toContain('--options typedoc.json');
    expect(docs).toContain('index.html');
    expect(docs).toContain('npm ci --no-audit --no-fund');
    expect(read('typedoc.json')).toContain('"treatWarningsAsErrors": true');
  });

  it('documents and enforces the generated-only coverage exclusion', () => {
    const config = read('vite.config.ts');
    expect(config).toContain('src/api/generated/**');
    expect(config).toContain('perFile: true');
    expect(config).toMatch(/lines: 100/);
    expect(config).toMatch(/branches: 100/);
    expect(config).toMatch(/functions: 100/);
    expect(config).toMatch(/statements: 100/);
  });

  it('contains only the generated declaration in the generated directory', () => {
    const dir = resolve(moduleRoot, 'src/api/generated');
    expect(readdirSync(dir).sort()).toEqual(['openapi.d.ts']);
    expect(read('src/api/generated/openapi.d.ts')).toMatch(/auto-generated by openapi-typescript/);
    expect(read('src/api/generated/openapi.d.ts')).toContain("'/api/v1/facilities'");
  });
});
