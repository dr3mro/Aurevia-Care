package com.aurevia.scheduling.checkin;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.Instant;
import java.time.OffsetDateTime;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import org.springframework.jdbc.core.RowMapper;
import org.springframework.jdbc.core.namedparam.MapSqlParameterSource;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.stereotype.Repository;

/**
 * SQL boundary for the check-in ledgers and the mutable worklist projection.
 *
 * <p>Every statement relies on the transaction-local tenant binding and the
 * forced row-level security of V12, so a row outside the active organization is
 * invisible rather than merely unfetched. Writes are scoped by the active
 {@code app_org()} and derive their actor from {@code app.actor} in triggers;
 * no caller-supplied organization or actor reaches a statement.</p>
 */
@Repository
public class WorklistRepository {

    private static final RowMapper<WorklistItem> ITEM_MAPPER = WorklistRepository::mapItem;

    private final NamedParameterJdbcTemplate jdbc;

    /**
     * Create the repository.
     *
     * @param jdbc shared named-parameter JDBC template
     */
    public WorklistRepository(NamedParameterJdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    /**
     * Append one immutable identity-verification record.
     *
     * @param id             opaque verification identifier generated by the caller
     * @param appointmentId  appointment whose identity was confirmed
     * @param patientId      verified patient identifier
     * @param facilityId     facility of the check-in
     * @param method         verification method key
     * @param identifiers    identifier categories used
     * @param alternateCode  named workflow code for an alternate path, or {@code null}
     * @param alternateReason reason for an alternate path, or {@code null}
     * @return number of inserted rows
     */
    public int insertVerification(String id, String appointmentId, String patientId, String facilityId,
                                  String method, List<String> identifiers, String alternateCode,
                                  String alternateReason) {
        return jdbc.update("""
                INSERT INTO public.check_in_verification
                    (organization_id, id, appointment_id, patient_id, facility_id, method,
                     identifiers, alternate_code, alternate_reason)
                VALUES (public.app_org(), CAST(:id AS uuid), CAST(:appointmentId AS uuid),
                        CAST(:patientId AS uuid), CAST(:facilityId AS uuid), :method,
                        CAST(:identifiers AS jsonb), :alternateCode, :alternateReason)
                """, new MapSqlParameterSource().addValue("id", id)
                .addValue("appointmentId", appointmentId)
                .addValue("patientId", patientId).addValue("facilityId", facilityId)
                .addValue("method", method)
                .addValue("identifiers", identifiersJson(identifiers))
                .addValue("alternateCode", alternateCode)
                .addValue("alternateReason", alternateReason));
    }

    /**
     * Check whether a successful identity verification exists for an appointment.
     *
     * @param appointmentId appointment identifier
     * @return {@code true} when a verification record is visible in this tenant
     */
    public boolean hasVerification(String appointmentId) {
        Boolean exists = jdbc.queryForObject("""
                SELECT EXISTS (SELECT 1 FROM public.check_in_verification
                                WHERE appointment_id = CAST(:appointmentId AS uuid))
                """, Map.of("appointmentId", appointmentId), Boolean.class);
        return Boolean.TRUE.equals(exists);
    }

    /**
     * Resolve the identifier of a facility by its tenant-local code.
     *
     * @param facilityCode facility code
     * @return the facility identifier when visible
     */
    public Optional<String> facilityId(String facilityCode) {
        return jdbc.query("""
                SELECT id::text FROM public.facility WHERE code = :facilityCode
                """, Map.of("facilityCode", facilityCode),
                (resultSet, rowNumber) -> resultSet.getString(1)).stream().findFirst();
    }

    /**
     * Ask the database whether a facility is outside the caller's assigned scope.
     *
     * <p>The fold is re-read inside the guarded transaction, so a scope change is
     * visible on the next request. The database answer is {@code false} for a member
     * with no recorded assignment and for the organization-wide oversight roles,
     * and {@code true} only when the member has assignments but not this facility.</p>
     *
     * @param subject      authenticated subject in the active organization
     * @param facilityCode tenant-local facility code being accessed
     * @return {@code true} when this facility must be refused to the subject
     */
    public boolean outsideAssignedFacilities(String subject, String facilityCode) {
        Boolean outside = jdbc.queryForObject(
                "SELECT public.is_facility_out_of_scope(:subject, :facilityCode)",
                Map.of("subject", subject, "facilityCode", facilityCode), Boolean.class);
        return Boolean.TRUE.equals(outside);
    }

    /**
     * Check that a patient is visible in the active organization.
     *
     * @param patientId patient identifier
     * @return {@code true} when the patient exists in this tenant
     */
    public boolean patientExists(String patientId) {
        Boolean exists = jdbc.queryForObject("""
                SELECT EXISTS (SELECT 1 FROM public.patient_record
                                WHERE id = CAST(:patientId AS uuid))
                """, Map.of("patientId", patientId), Boolean.class);
        return Boolean.TRUE.equals(exists);
    }

    /**
     * Insert a worklist row for a scheduled appointment or an unscheduled arrival.
     *
     * @param appointmentId  appointment identifier, or {@code null} for a walk-in
     * @param intakeReason   unscheduled reason, or {@code null} for a booking
     * @param patientId      patient identifier
     * @param facilityId     facility identifier
     * @param priority       resolved site priority
     * @param assigneeSubject initial assignee, or {@code null}
     * @param assignedAt     assignment timestamp, or {@code null}
     * @return the generated worklist entry identifier
     */
    public String insertItem(String appointmentId, String intakeReason, String patientId,
                             String facilityId, int priority, String assigneeSubject,
                             Instant assignedAt) {
        return jdbc.queryForObject("""
                INSERT INTO public.worklist_entry
                    (organization_id, appointment_id, intake_reason, patient_id, facility_id,
                     priority, assignee_subject, assigned_at)
                VALUES (public.app_org(), CAST(:appointmentId AS uuid), :intakeReason,
                        CAST(:patientId AS uuid), CAST(:facilityId AS uuid), :priority,
                        :assigneeSubject, CAST(:assignedAt AS timestamptz))
                RETURNING id::text
                """, new MapSqlParameterSource().addValue("appointmentId", appointmentId)
                .addValue("intakeReason", intakeReason).addValue("patientId", patientId)
                .addValue("facilityId", facilityId).addValue("priority", priority)
                .addValue("assigneeSubject", assigneeSubject)
                .addValue("assignedAt", instantText(assignedAt)), String.class);
    }

    /**
     * Read one worklist row, locking it for the current transaction.
     *
     * @param id worklist entry identifier
     * @return the locked entry when visible
     */
    public Optional<WorklistItem> findItemForUpdate(String id) {
        return jdbc.query(SELECT_ITEM + " WHERE w.id = CAST(:id AS uuid) FOR UPDATE OF w",
                Map.of("id", id), ITEM_MAPPER).stream().findFirst();
    }

    /**
     * Replace the current assignment and/or priority with an optimistic-version guard.
     *
     * @param id              worklist entry identifier
     * @param expectedVersion version read by the caller
     * @param assigneeSubject new assignee, or {@code null} to clear
     * @param assignedAt      assignment timestamp, or {@code null} when unchanged
     * @param priority        current site priority
     * @return number of updated rows; {@code 0} means the version moved underneath
     */
    public int updateItem(String id, int expectedVersion, String assigneeSubject, Instant assignedAt,
                          int priority) {
        return jdbc.update("""
                UPDATE public.worklist_entry
                   SET assignee_subject = :assigneeSubject,
                       assigned_at = CAST(:assignedAt AS timestamptz),
                       priority = :priority,
                       version = version + 1
                 WHERE id = CAST(:id AS uuid) AND version = :expectedVersion
                """, new MapSqlParameterSource().addValue("id", id)
                .addValue("expectedVersion", expectedVersion).addValue("assigneeSubject", assigneeSubject)
                .addValue("assignedAt", instantText(assignedAt)).addValue("priority", priority));
    }

    /**
     * Append one immutable assignment or transfer event.
     *
     * @param event immutable handoff event to append
     */
    public void insertHandoff(HandoffEvent event) {
        jdbc.update("""
                INSERT INTO public.handoff_event
                    (organization_id, id, worklist_entry_id, from_subject, to_subject, reason)
                VALUES (public.app_org(), CAST(:id AS uuid), CAST(:itemId AS uuid),
                        :fromSubject, :toSubject, :reason)
                """, new MapSqlParameterSource().addValue("id", event.id())
                .addValue("itemId", event.itemId())
                .addValue("fromSubject", event.fromSubject()).addValue("toSubject", event.toSubject())
                .addValue("reason", event.reason()));
    }

    /**
     * List the worklist of one facility, ordered by scheduled time then priority.
     *
     * @param facilityCode facility code that scopes the worklist
     * @param limit        maximum rows to return
     * @return the ordered worklist items
     */
    public List<WorklistItem> listWorklist(String facilityCode, int limit) {
        return jdbc.query(SELECT_ITEM + """
                 WHERE f.code = :facilityCode
                 ORDER BY COALESCE(a.starts_at, w.created_at) ASC,
                          w.priority DESC, w.created_at ASC, w.id ASC
                 LIMIT :limit
                """, new MapSqlParameterSource().addValue("facilityCode", facilityCode)
                .addValue("limit", limit), ITEM_MAPPER);
    }

    private static final String SELECT_ITEM = """
            SELECT w.id::text AS id, w.appointment_id::text AS appointment_id,
                   w.intake_reason, w.patient_id::text AS patient_id,
                   f.code AS facility_code, a.starts_at, w.priority,
                   w.assignee_subject, w.assigned_at, w.version
              FROM public.worklist_entry w
              JOIN public.facility f
                ON f.organization_id = w.organization_id AND f.id = w.facility_id
              LEFT JOIN public.appointment a
                ON a.organization_id = w.organization_id AND a.id = w.appointment_id
            """;

    private static String identifiersJson(List<String> identifiers) {
        StringBuilder json = new StringBuilder("[");
        for (int index = 0; index < identifiers.size(); index++) {
            if (index > 0) {
                json.append(',');
            }
            json.append('"').append(identifiers.get(index)).append('"');
        }
        return json.append(']').toString();
    }

    private static String instantText(Instant instant) {
        return instant == null ? null : instant.toString();
    }

    private static Instant instant(ResultSet resultSet, String column) throws SQLException {
        OffsetDateTime value = resultSet.getObject(column, OffsetDateTime.class);
        return value == null ? null : value.toInstant();
    }

    private static WorklistItem mapItem(ResultSet resultSet, int rowNumber) throws SQLException {
        return new WorklistItem(resultSet.getString("id"), resultSet.getString("appointment_id"),
                resultSet.getString("intake_reason"), resultSet.getString("patient_id"),
                resultSet.getString("facility_code"), instant(resultSet, "starts_at"),
                resultSet.getInt("priority"), resultSet.getString("assignee_subject"),
                instant(resultSet, "assigned_at"), resultSet.getInt("version"));
    }
}
