package com.aurevia.smartclinic.tenant.clauses;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.UUID;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpMethod;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.web.client.RestClient;

import com.aurevia.smartclinic.tenant.TenantContext;
import com.aurevia.smartclinic.tenant.TenantGuardTransactionManager;

/**
 * ARC-01 clause 1 acceptance on real PostgreSQL with synthetic fixtures only.
 *
 * <p>The invariant under test is that a tenant-owned record is keyed by the
 * pair {@code (organization_id, opaque uuid id)}: the organization is a required
 * column, the identifier is a UUID generated by the database, and a foreign key
 * cannot reference an opaque identifier without its owning organization.</p>
 *
 * <p>The metadata assertions are scoped to the foundational tenant-owned tables
 * defined by the tenant schema ({@code V1__tenant_schema.sql}), which are the
 * records this clause names. Later feature modules with deliberately named or
 * non-UUID keys are out of scope for this proof. No production code is added;
 * a durable row is read back through the normal HTTP entry point and through
 * the application role under forced row-level security.</p>
 */
@Tag("integration")
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT,
        properties = "spring.datasource.url=jdbc:postgresql://127.0.0.1:5432/smartclinic_arc01_clause1_it")
@ActiveProfiles("synthetic-auth")
class TenantOwnedRecordsHaveOrganizationIdOpaqueTest {

    static final String ORG_A = "11111111-1111-1111-1111-111111111111";
    static final String ORG_B = "22222222-2222-2222-2222-222222222222";
    static final String URL = "jdbc:postgresql://127.0.0.1:5432/smartclinic_arc01_clause1_it";
    static final String MIGRATE = "smartclinic_migrate";
    static final String ADMIN = System.getenv().getOrDefault(
            "SMARTCLINIC_PG_ADMIN", System.getProperty("user.name"));
    static final String CODE = "ARC01-CLAUSE1";
    static final List<String> TENANT_OWNED_TABLES = List.of(
            "user_identity", "facility", "membership", "audit_event");

    /** The two halves of a tenant-owned durable key, as stored in the database. */
    private record StoredKey(String organizationId, String id) {
    }

    @Autowired
    JdbcTemplate jdbcTemplate;

    @Autowired
    TenantGuardTransactionManager transactionManager;

    RestClient rest;

    @BeforeEach
    void initRestClient(@LocalServerPort int port) {
        rest = RestClient.builder().baseUrl("http://localhost:" + port).build();
    }

    @BeforeAll
    static void prepare() throws Exception {
        try (Connection root = DriverManager.getConnection(
                "jdbc:postgresql://127.0.0.1:5432/postgres", ADMIN, "");
             Statement statement = root.createStatement()) {
            statement.execute("DO $$ BEGIN "
                    + "IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='smartclinic_migrate') THEN "
                    + "CREATE ROLE smartclinic_migrate LOGIN NOBYPASSRLS NOCREATEDB NOCREATEROLE; END IF; "
                    + "IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='smartclinic_app') THEN "
                    + "CREATE ROLE smartclinic_app LOGIN NOBYPASSRLS NOCREATEDB NOCREATEROLE; END IF; END $$;");
            statement.execute("DROP DATABASE IF EXISTS smartclinic_arc01_clause1_it WITH (FORCE)");
            statement.execute("CREATE DATABASE smartclinic_arc01_clause1_it OWNER smartclinic_migrate");
        }
        Flyway.configure()
                .dataSource(URL, MIGRATE, "")
                .locations("filesystem:../../db/migrations")
                .load().migrate();

        try (Connection connection = connect(MIGRATE);
             Statement statement = connection.createStatement()) {
            seed(statement, ORG_A, "admin-a");
            seed(statement, ORG_B, "admin-b");
            // The default-generated id is the durable opaque identifier read back below.
            statement.execute("SET app.current_org = '" + ORG_A + "'");
            statement.execute("INSERT INTO public.facility (organization_id, code, name) "
                    + "VALUES ('" + ORG_A + "', '" + CODE + "', 'Arc One')");
        }
    }

    @AfterAll
    static void cleanUp() throws Exception {
        try (Connection root = DriverManager.getConnection(
                "jdbc:postgresql://127.0.0.1:5432/postgres", ADMIN, "");
             Statement statement = root.createStatement()) {
            statement.execute("DROP DATABASE IF EXISTS smartclinic_arc01_clause1_it WITH (FORCE)");
        }
    }

    /** Connect to the dedicated synthetic database as a named role. */
    private static Connection connect(String role) throws SQLException {
        return DriverManager.getConnection(URL, role, "");
    }

    /** Seed one tenant with an active administrator and its tenant-owned membership. */
    private static void seed(Statement statement, String org, String subject) throws SQLException {
        statement.execute("SET app.current_org = '" + org + "'");
        statement.execute("SET app.actor = '" + subject + "'");
        statement.execute("INSERT INTO public.organization (organization_id, display_name) "
                + "VALUES ('" + org + "', 'Org " + subject + "')");
        statement.execute("INSERT INTO public.user_identity (organization_id, subject, display_name) "
                + "VALUES ('" + org + "', '" + subject + "', '" + subject + "')");
        statement.execute("INSERT INTO public.membership (organization_id, user_id, status) "
                + "SELECT '" + org + "', id, 'active' FROM public.user_identity WHERE subject = '" + subject + "'");
        statement.execute("INSERT INTO public.role_assignment (organization_id, membership_id, role_key, granted_by) "
                + "SELECT '" + org + "', m.id, 'tenant_admin', u.id FROM public.membership m "
                + "JOIN public.user_identity u ON u.organization_id = m.organization_id AND u.id = m.user_id "
                + "WHERE u.subject = '" + subject + "'");
    }

    /** Read one metadata attribute of a foundational tenant-owned column from the catalog. */
    private static String columnAttribute(String table, String column, String attribute) throws SQLException {
        try (Connection connection = connect(MIGRATE);
             Statement statement = connection.createStatement();
             ResultSet rows = statement.executeQuery("SELECT " + attribute + " FROM information_schema.columns "
                     + "WHERE table_schema = 'public' AND table_name = '" + table
                     + "' AND column_name = '" + column + "'")) {
            assertTrue(rows.next(), "missing column " + table + "." + column);
            return rows.getString(1);
        }
    }

    /** Read the seeded row as the non-owner application role under forced RLS. */
    private StoredKey storedKey() {
        TenantContext.set(new TenantContext(ORG_A, "admin-a", TenantContext.PURPOSE, "arc01-clause1-it"));
        try {
            return new TransactionTemplate(transactionManager).execute(status -> jdbcTemplate.queryForObject(
                    "SELECT organization_id::text, id::text FROM public.facility WHERE code = '" + CODE + "'",
                    (row, number) -> new StoredKey(row.getString(1), row.getString(2))));
        } finally {
            TenantContext.clear();
        }
    }

    /** Issue a synthetic-authenticated request through the normal HTTP entry point. */
    private ResponseEntity<String> get(String uri, String subject, String organization) {
        HttpHeaders headers = new HttpHeaders();
        if (subject != null) {
            headers.set("X-Synthetic-Subject", subject);
        }
        if (organization != null) {
            headers.set("X-Active-Organization", organization);
        }
        headers.setContentType(MediaType.APPLICATION_JSON);
        return rest.get().uri(uri)
                .headers(httpHeaders -> httpHeaders.addAll(headers))
                .retrieve().onStatus(status -> true, (request, response) -> { })
                .toEntity(String.class);
    }

    /**
     * The foundational tenant-owned tables require an organization and generate
     * an opaque UUID id, and a durable record exposes its organization through
     * the API and carries a parseable UUID id when read back under forced RLS.
     */
    @Test
    void tenantOwnedTablesCarryOrganizationIdAndOpaqueUuidId() throws SQLException {
        for (String table : TENANT_OWNED_TABLES) {
            assertEquals("uuid", columnAttribute(table, "organization_id", "data_type"), table);
            assertEquals("NO", columnAttribute(table, "organization_id", "is_nullable"), table);
            assertEquals("uuid", columnAttribute(table, "id", "data_type"), table);
            assertTrue(columnAttribute(table, "id", "column_default").contains("gen_random_uuid()"), table);
        }

        ResponseEntity<String> response = get("/api/v1/facilities/" + CODE, "admin-a", ORG_A);
        assertEquals(HttpStatus.OK, response.getStatusCode(), response.getBody());
        assertTrue(response.getBody().contains(ORG_A), response.getBody());

        StoredKey key = storedKey();
        assertEquals(ORG_A, key.organizationId());
        assertNotNull(key.id());
        assertEquals(key.id(), UUID.fromString(key.id()).toString(), "the durable id must be an opaque UUID");
    }

    /**
     * A foreign key cannot reference an opaque identifier without its owning
     * organization: a membership for organization B with organization A's user id
     * is refused by the composite foreign key with SQLState 23503.
     */
    @Test
    void crossTenantForeignKeyIsRefused() throws SQLException {
        String userA;
        try (Connection connection = connect(MIGRATE);
             Statement statement = connection.createStatement()) {
            statement.execute("SET app.current_org = '" + ORG_A + "'");
            try (ResultSet rows = statement.executeQuery("SELECT id::text FROM public.user_identity "
                    + "WHERE subject = 'admin-a'")) {
                assertTrue(rows.next());
                userA = rows.getString(1);
            }
        }

        try (Connection connection = connect(MIGRATE);
             Statement statement = connection.createStatement()) {
            // The organization matches the active tenant, so RLS cannot mask the FK.
            statement.execute("SET app.current_org = '" + ORG_B + "'");
            SQLException refused = assertThrows(SQLException.class, () -> statement.execute(
                    "INSERT INTO public.membership (organization_id, user_id) VALUES ('"
                            + ORG_B + "', '" + userA + "')"));
            assertEquals("23503", refused.getSQLState(), refused.getMessage());
            assertTrue(refused.getMessage().contains("membership"), refused.getMessage());
        }
    }

    /**
     * A tenant-owned insert without an organization identifier is refused by the
     * NOT NULL constraint with SQLState 23502. A superuser connection is used so
     * forced RLS cannot turn this into a policy violation before the table
     * constraint is evaluated; no production role is widened by this test.
     */
    @Test
    void missingOrganizationIdIsRefused() throws SQLException {
        try (Connection connection = connect(ADMIN);
             Statement statement = connection.createStatement()) {
            SQLException refused = assertThrows(SQLException.class, () -> statement.execute(
                    "INSERT INTO public.facility (code, name) VALUES ('ARC01-NO-ORG', 'No organization')"));
            assertEquals("23502", refused.getSQLState(), refused.getMessage());
            assertTrue(refused.getMessage().contains("organization_id"), refused.getMessage());
        }
    }
}
