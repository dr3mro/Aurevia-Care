-- Requirement IDs: ARC-01, ARC-02, OPS-02
-- Change: expand
-- Durable MSG-04 typed patient instructions. Each aggregate the instruction
-- store owns gets one tenant-owned table: approved templates, immutable-sent
-- revisions whose lifecycle state advances by a narrow UPDATE, and append-only
-- notification facts. Every table carries an organization_id, a server creation
-- instant and forced row-level security; a new table is not covered by V2's
-- static table list, so every policy, grant and trigger is declared here. The
-- migration is additive only.
--
-- Local identifiers are unique only inside a tenant, so every primary key and
-- business key includes organization_id. Identical local identifiers in two
-- tenants therefore remain isolated. Facts are append-only and carry no UPDATE,
-- DELETE or TRUNCATE grant; a reject-mutation trigger protects them for every
-- role, including the migration owner. Roles, verified charts, connections and
-- staff-to-unit assignment are read from the authoritative V4, V10, V60 and V63
-- folds and reference tables; no second copy is projected here.

CREATE TABLE public.instruction_template (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              text NOT NULL,
    unit_id         text NOT NULL,
    kind            text NOT NULL CHECK (kind IN
        ('collection', 'imaging_preparation', 'therapy_home', 'visit_follow_up',
         'pharmacy_pickup', 'general')),
    title           text NOT NULL,
    body            text NOT NULL,
    language        text NOT NULL,
    version         integer NOT NULL CHECK (version >= 1),
    approved_by     text NOT NULL,
    approved_at     timestamptz NOT NULL,
    clinical        boolean NOT NULL,
    context_type    text CHECK (context_type IN
        ('appointment', 'order', 'referral', 'prescription', 'encounter')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id)
);

CREATE TABLE public.instruction_revision (
    organization_id   uuid NOT NULL REFERENCES public.organization(organization_id),
    thread_id         text NOT NULL,
    revision          integer NOT NULL CHECK (revision >= 1),
    template_id       text,
    kind              text NOT NULL CHECK (kind IN
        ('collection', 'imaging_preparation', 'therapy_home', 'visit_follow_up',
         'pharmacy_pickup', 'general')),
    title             text NOT NULL,
    body              text NOT NULL,
    language          text NOT NULL,
    author_subject    text NOT NULL,
    author_role       text NOT NULL,
    unit_id           text NOT NULL,
    connection_id     text NOT NULL,
    patient_id        text NOT NULL,
    issued_at         timestamptz NOT NULL,
    action_due_at     timestamptz,
    context_type      text CHECK (context_type IN
        ('appointment', 'order', 'referral', 'prescription', 'encounter')),
    context_id        text,
    attachment_ids    text[] NOT NULL DEFAULT '{}',
    state             text NOT NULL CHECK (state IN
        ('draft', 'sent', 'superseded', 'withdrawn')),
    superseded_by     integer,
    replaces_revision integer,
    withdrawal_reason text,
    created_at        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, thread_id, revision)
);

CREATE TABLE public.instruction_fact (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    thread_id       text NOT NULL,
    revision        integer NOT NULL CHECK (revision >= 1),
    type            text NOT NULL CHECK (type IN
        ('sent', 'replaced', 'superseded', 'withdrawn', 'dispatched')),
    recipient       text,
    occurred_at     timestamptz NOT NULL,
    note            text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['instruction_template', 'instruction_revision', 'instruction_fact']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format($p$CREATE POLICY tenant_isolation ON public.%I
             USING (organization_id = public.app_org())
             WITH CHECK (organization_id = public.app_org())$p$, t);
    END LOOP;

    -- Facts are immutable for every role, including the migration owner; a
    -- GRANT alone would not cover the owner. The state-bearing revision table
    -- is deliberately excluded so supersede and withdraw can advance one row.
    EXECUTE $d$CREATE TRIGGER instruction_fact_no_update_delete
        BEFORE UPDATE OR DELETE ON public.instruction_fact
        FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
    EXECUTE $d$CREATE TRIGGER instruction_fact_no_truncate
        BEFORE TRUNCATE ON public.instruction_fact
        FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
END $$;

-- Reapproval of a template replaces the approved version in place, matching the
-- port's put semantics; revision state advances by a single guarded UPDATE.
-- Facts are declaration-only: no UPDATE or DELETE permission is ever granted.
GRANT SELECT, INSERT, UPDATE ON public.instruction_template TO smartclinic_app;
GRANT SELECT, INSERT, UPDATE ON public.instruction_revision TO smartclinic_app;
GRANT SELECT, INSERT ON public.instruction_fact TO smartclinic_app;
REVOKE DELETE, TRUNCATE ON public.instruction_template FROM smartclinic_app;
REVOKE DELETE, TRUNCATE ON public.instruction_revision FROM smartclinic_app;
REVOKE UPDATE, DELETE, TRUNCATE ON public.instruction_fact FROM smartclinic_app;
