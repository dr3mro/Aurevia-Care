-- Requirement IDs: MSG-06, ARC-01, ARC-02, OPS-02
-- Change: expand
-- Durable MSG-06 service profiles and the authorization facts that decide who may
-- act for a care unit. Each aggregate the service-profile store owns gets one
-- tenant-owned table: immutable profile versions, non-sensitive work facts, the
-- authorization audit ledger and the staff-to-unit assignment reference. Every
-- table carries an organization_id, a server creation instant and forced row-level
-- security; a new table is not covered by V2's static table list, so every policy,
-- grant and trigger is declared here. The migration is additive only.
--
-- Local identifiers are unique only inside a tenant, so every primary key and
-- every business key includes organization_id. Identical local identifiers in two
-- tenants therefore remain isolated. Append-only facts receive no UPDATE, DELETE
-- or TRUNCATE grant and are protected by reject-mutation triggers for every role,
-- including the migration owner. A profile version is immutable except for the
-- single, one-way draft-to-approved transition, which a trigger confines to the
-- approval fields; the unique (organization_id, unit_id, version) key makes the
-- version sequence durable rather than process-local.
--
-- Membership, roles, verified charts and patient-unit connections are read from
-- the authoritative V4, V10 and V60 folds and the V60 care-unit table; no second
-- copy is projected here. Staff-to-unit assignment has no authoritative durable
-- source in the current schema, so service_profile_unit_assignment is a
-- SELECT/INSERT reference for an authorized setup path, mirroring the
-- instruction_fact_unit_assignment precedent in V63.

CREATE TABLE public.service_profile (
    organization_id          uuid NOT NULL REFERENCES public.organization(organization_id),
    id                       uuid NOT NULL,
    unit_id                  uuid NOT NULL,
    version                  integer NOT NULL CHECK (version >= 1),
    status                   text NOT NULL CHECK (status IN ('draft', 'approved')),
    time_zone                text NOT NULL,
    windows                  text[] NOT NULL CHECK (cardinality(windows) >= 1),
    response_target_minutes  integer NOT NULL CHECK (response_target_minutes BETWEEN 1 AND 1440),
    topics                   text[] NOT NULL,
    urgent_instructions      jsonb NOT NULL CHECK (jsonb_typeof(urgent_instructions) = 'array'),
    queue_owner              text NOT NULL CHECK (btrim(queue_owner) <> ''),
    backup_coverage          text[] NOT NULL,
    escalation_channel       text NOT NULL,
    urgent_channel           text NOT NULL,
    downtime_channel         text NOT NULL,
    created_by               text NOT NULL,
    approved_by              text,
    approved_at              timestamptz,
    approval_note            text,
    effective_from           timestamptz NOT NULL,
    created_at               timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, unit_id, version),
    CHECK ((status = 'draft'
               AND approved_by IS NULL AND approved_at IS NULL AND approval_note IS NULL)
        OR (status = 'approved'
               AND approved_by IS NOT NULL AND approved_at IS NOT NULL))
);

CREATE TABLE public.service_profile_work_item (
    organization_id          uuid NOT NULL REFERENCES public.organization(organization_id),
    id                       uuid NOT NULL,
    seq                      bigint GENERATED BY DEFAULT AS IDENTITY,
    unit_id                  uuid NOT NULL,
    state                    text NOT NULL CHECK (state IN
        ('awaiting_staff', 'awaiting_patient', 'resolved', 'closed')),
    assignee                 text,
    occurred_at              timestamptz NOT NULL,
    last_staff_response_at   timestamptz,
    notification_failed      boolean NOT NULL,
    created_at               timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.service_profile_audit (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    subject         text NOT NULL,
    action          text NOT NULL,
    resource_id     text NOT NULL,
    outcome         text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.service_profile_unit_assignment (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    subject         text NOT NULL,
    unit_id         uuid NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, subject, unit_id)
);

-- Only the approval of a draft may update a profile row. All content fields are
-- compared so a caller cannot smuggle a new version or changed guidance into the
-- transition; every other mutation is rejected for every role, including the
-- migration owner.
CREATE OR REPLACE FUNCTION public.service_profile_approval_transition()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog
AS $$
BEGIN
    -- An approval stamps the three approval fields exactly once. The status
    -- CHECK makes most of this unreachable for stored rows, but the guard keeps
    -- the invariant true for a bypassing owner as well.
    IF OLD.approved_by IS NOT NULL OR OLD.approved_at IS NOT NULL
       OR OLD.approval_note IS NOT NULL
       OR NEW.approved_by IS NULL OR NEW.approved_at IS NULL THEN
        RAISE EXCEPTION 'service profile approval fields may only be stamped once'
            USING ERRCODE = '44000';
    END IF;
    -- Named approval requires a distinct approver (mirrored from MSG-06).
    IF NEW.approved_by = OLD.created_by THEN
        RAISE EXCEPTION 'the profile creator cannot be the named approver'
            USING ERRCODE = '44000';
    END IF;
    IF OLD.status <> 'draft' OR NEW.status <> 'approved'
       OR NEW.organization_id IS DISTINCT FROM OLD.organization_id
       OR NEW.id IS DISTINCT FROM OLD.id
       OR NEW.unit_id IS DISTINCT FROM OLD.unit_id
       OR NEW.version IS DISTINCT FROM OLD.version
       OR NEW.time_zone IS DISTINCT FROM OLD.time_zone
       OR NEW.windows IS DISTINCT FROM OLD.windows
       OR NEW.response_target_minutes IS DISTINCT FROM OLD.response_target_minutes
       OR NEW.topics IS DISTINCT FROM OLD.topics
       OR NEW.urgent_instructions IS DISTINCT FROM OLD.urgent_instructions
       OR NEW.queue_owner IS DISTINCT FROM OLD.queue_owner
       OR NEW.backup_coverage IS DISTINCT FROM OLD.backup_coverage
       OR NEW.escalation_channel IS DISTINCT FROM OLD.escalation_channel
       OR NEW.urgent_channel IS DISTINCT FROM OLD.urgent_channel
       OR NEW.downtime_channel IS DISTINCT FROM OLD.downtime_channel
       OR NEW.created_by IS DISTINCT FROM OLD.created_by
       OR NEW.effective_from IS DISTINCT FROM OLD.effective_from
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'service_profile only permits the draft to approved transition'
            USING ERRCODE = '44000';
    END IF;
    RETURN NEW;
END $$;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'service_profile', 'service_profile_work_item',
        'service_profile_audit', 'service_profile_unit_assignment'
    ]
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format($p$CREATE POLICY tenant_isolation ON public.%I
             USING (organization_id = public.app_org())
             WITH CHECK (organization_id = public.app_org())$p$, t);
    END LOOP;

    -- Immutable facts reject mutation for every role, including the owner.
    FOREACH t IN ARRAY ARRAY[
        'service_profile_work_item', 'service_profile_audit',
        'service_profile_unit_assignment'
    ]
    LOOP
        EXECUTE format($d$CREATE TRIGGER %I_no_update_delete
            BEFORE UPDATE OR DELETE ON public.%I
            FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation()$d$, t, t);
        EXECUTE format($d$CREATE TRIGGER %I_no_truncate
            BEFORE TRUNCATE ON public.%I
            FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation()$d$, t, t);
    END LOOP;

    EXECUTE $d$CREATE TRIGGER service_profile_no_delete
        BEFORE DELETE ON public.service_profile
        FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
    EXECUTE $d$CREATE TRIGGER service_profile_no_truncate
        BEFORE TRUNCATE ON public.service_profile
        FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
    EXECUTE $d$CREATE TRIGGER service_profile_approval_only
        BEFORE UPDATE ON public.service_profile
        FOR EACH ROW EXECUTE FUNCTION public.service_profile_approval_transition()$d$;
END $$;

-- Every write is made by an authorized workflow through the runtime role.
GRANT SELECT, INSERT ON public.service_profile TO orevia_app;
GRANT SELECT, INSERT ON public.service_profile_work_item TO orevia_app;
GRANT SELECT, INSERT ON public.service_profile_audit TO orevia_app;
GRANT SELECT, INSERT ON public.service_profile_unit_assignment TO orevia_app;

GRANT UPDATE (status, approved_by, approved_at, approval_note)
    ON public.service_profile TO orevia_app;

REVOKE UPDATE, DELETE, TRUNCATE ON public.service_profile_work_item FROM orevia_app;
REVOKE UPDATE, DELETE, TRUNCATE ON public.service_profile_audit FROM orevia_app;
REVOKE UPDATE, DELETE, TRUNCATE ON public.service_profile_unit_assignment FROM orevia_app;
REVOKE DELETE, TRUNCATE ON public.service_profile FROM orevia_app;
