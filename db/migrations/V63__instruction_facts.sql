-- Requirement IDs: ARC-01, ARC-02, OPS-02
-- Change: expand
-- Durable MSG-05 instruction facts. Each aggregate the instruction-fact store
-- owns gets one tenant-owned table: immutable instruction revisions, publication,
-- generic dispatch, first view, receipt acknowledgment, the state-bearing
-- follow-up, idempotency digests and the non-sensitive audit ledger. Every table
-- carries an organization_id, a server creation instant and forced row-level
-- security; a new table is not covered by V2's static table list, so every
-- policy, grant and trigger is declared here. The migration is additive only.
--
-- Local identifiers are unique only inside a tenant, so every primary key and
-- every business key includes organization_id. Identical local identifiers in
-- two tenants therefore remain isolated. Append-only facts receive no UPDATE,
-- DELETE or TRUNCATE grant and are protected by reject-mutation triggers for
-- every role, including the migration owner. The follow-up is the sole
-- state-bearing aggregate: resolving it is an UPDATE of a single routed row and
-- is the only table here with an UPDATE grant.
--
-- Membership, roles, verified charts and patient-unit connections are read from
-- the authoritative V4 and V10 folds and the V60 connection table; no second
-- copy is projected here. Staff-to-unit assignment has no authoritative durable
-- source in the current schema, so instruction_fact_unit_assignment is a
-- SELECT/INSERT reference for an authorized setup path, mirroring the
-- messaging_resource precedent in V62.

CREATE TABLE public.instruction_fact_instruction (
    organization_id          uuid NOT NULL REFERENCES public.organization(organization_id),
    id                       uuid NOT NULL,
    revision                 integer NOT NULL CHECK (revision >= 1),
    patient_id               uuid NOT NULL,
    unit_id                  uuid NOT NULL,
    content_ref              text NOT NULL,
    requires_acknowledgment  boolean NOT NULL,
    acknowledgment_due_at    timestamptz,
    created_at               timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id, revision)
);

CREATE TABLE public.instruction_fact_publication (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    instruction_id  uuid NOT NULL,
    revision        integer NOT NULL CHECK (revision >= 1),
    actor           text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, instruction_id, revision),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.instruction_fact_dispatch (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    instruction_id  uuid NOT NULL,
    revision        integer NOT NULL CHECK (revision >= 1),
    generic_key     text NOT NULL,
    correlation_id  text,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.instruction_fact_first_view (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    instruction_id  uuid NOT NULL,
    revision        integer NOT NULL CHECK (revision >= 1),
    actor           text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, instruction_id, revision, actor),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.instruction_fact_acknowledgment (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    instruction_id  uuid NOT NULL,
    revision        integer NOT NULL CHECK (revision >= 1),
    actor           text NOT NULL,
    scope           text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, instruction_id, revision, actor),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.instruction_fact_follow_up (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    instruction_id  uuid NOT NULL,
    revision        integer NOT NULL CHECK (revision >= 1),
    unit_id         uuid NOT NULL,
    routed_at       timestamptz NOT NULL,
    state           text NOT NULL CHECK (state IN ('open', 'routed', 'resolved')),
    resolved_by     text,
    resolved_at     timestamptz,
    reason          text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, instruction_id, revision),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.instruction_fact_client_digest (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    subject         text NOT NULL,
    action          text NOT NULL,
    client_id       text NOT NULL,
    digest          text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, subject, action, client_id)
);

CREATE TABLE public.instruction_fact_audit (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    subject         text NOT NULL,
    action          text NOT NULL,
    resource_id     text NOT NULL,
    outcome         text NOT NULL,
    purpose         text,
    scope           text,
    correlation_id  text,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.instruction_fact_unit_assignment (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    subject         text NOT NULL,
    unit_id         uuid NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, subject, unit_id)
);

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'instruction_fact_instruction', 'instruction_fact_publication',
        'instruction_fact_dispatch', 'instruction_fact_first_view',
        'instruction_fact_acknowledgment', 'instruction_fact_follow_up',
        'instruction_fact_client_digest', 'instruction_fact_audit',
        'instruction_fact_unit_assignment'
    ]
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format($p$CREATE POLICY tenant_isolation ON public.%I
             USING (organization_id = public.app_org())
             WITH CHECK (organization_id = public.app_org())$p$, t);
    END LOOP;

    -- Immutable facts reject mutation for every role, including the owner;
    -- a GRANT alone would not cover the migration owner. The follow-up is the
    -- only state-bearing aggregate and is deliberately not in this list.
    FOREACH t IN ARRAY ARRAY[
        'instruction_fact_instruction', 'instruction_fact_publication',
        'instruction_fact_dispatch', 'instruction_fact_first_view',
        'instruction_fact_acknowledgment', 'instruction_fact_client_digest',
        'instruction_fact_audit', 'instruction_fact_unit_assignment'
    ]
    LOOP
        EXECUTE format($d$CREATE TRIGGER %I_no_update_delete
            BEFORE UPDATE OR DELETE ON public.%I
            FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation()$d$, t, t);
        EXECUTE format($d$CREATE TRIGGER %I_no_truncate
            BEFORE TRUNCATE ON public.%I
            FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation()$d$, t, t);
    END LOOP;
END $$;

