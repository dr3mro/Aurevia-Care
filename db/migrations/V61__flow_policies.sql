-- Requirement IDs: ARC-01, ARC-02, OPS-02
-- Change: expand
-- Durable patient-flow presentation policy: approved policy versions, the
-- generic-notice catalog and non-sensitive flow access facts. Each table is
-- tenant-owned, carries a creation instant and is protected by forced row-level
-- security; a new table is not covered by V2's static table list, so every
-- policy, grant and trigger is declared here. The migration is additive only.
--
-- Local identifiers are unique only inside a tenant, so every primary key and
-- the business keys include organization_id. Identical local keys in two tenants
-- therefore remain isolated. The three tables are append-only for the runtime
-- role: policy and notices are approved configuration written by an authorized
-- administration path, and access facts are immutable audit records. No UPDATE
-- or DELETE grant is given to orevia_app.

CREATE TABLE public.flow_policy (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    locale          text NOT NULL CHECK (locale IN ('en', 'ar')),
    platform        text NOT NULL CHECK (platform IN ('ios', 'android')),
    version         integer NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, locale, platform)
);

CREATE TABLE public.flow_approved_notice (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    notice_kind     text NOT NULL CHECK (notice_kind IN
        ('appointment_status', 'new_message', 'new_instruction',
         'reauth_required', 'account_locked', 'support_reply')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, notice_kind)
);

CREATE TABLE public.flow_access_audit (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    subject         text NOT NULL,
    purpose         text,
    action          text NOT NULL,
    correlation_id  text,
    outcome         text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['flow_policy', 'flow_approved_notice', 'flow_access_audit']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format($p$CREATE POLICY tenant_isolation ON public.%I
             USING (organization_id = public.app_org())
             WITH CHECK (organization_id = public.app_org())$p$, t);
    END LOOP;

    -- The access-fact ledger is append-only for every role, including the
    -- migration owner; a GRANT alone would not cover the owner.
    EXECUTE $d$CREATE TRIGGER flow_access_audit_no_update_delete
        BEFORE UPDATE OR DELETE ON public.flow_access_audit
        FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
    EXECUTE $d$CREATE TRIGGER flow_access_audit_no_truncate
        BEFORE TRUNCATE ON public.flow_access_audit
        FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
END $$;

-- Approved configuration and audit facts are written only by authorized
-- setup/admin paths; the runtime role can read and (for audit) append.
GRANT SELECT ON public.flow_policy TO orevia_app;
GRANT SELECT ON public.flow_approved_notice TO orevia_app;
GRANT SELECT, INSERT ON public.flow_access_audit TO orevia_app;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.flow_policy FROM orevia_app;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.flow_approved_notice FROM orevia_app;
REVOKE UPDATE, DELETE, TRUNCATE ON public.flow_access_audit FROM orevia_app;
