-- Requirement IDs: PAT-03, IAM-05, ARC-02
-- Change: expand
-- Durable patient access state for the messaging.enrollment domain.
--
-- V10's patient_account is immutable (no UPDATE/DELETE trigger) and its
-- account_invitation has a foreign key to an account, so neither can hold a
-- lockout counter or an invitation issued before an account exists. This
-- migration adds a current-state projection for accounts, single-use
-- invitations whose only stored credential is a SHA-256 code hash, single-use
-- purpose-bound tokens whose only stored credential is a SHA-256 token hash,
-- support cases and two append-only ledgers. No existing table is altered.
--
-- Every table is tenant-owned: organization_id is in every key, forced RLS
-- confines each statement to public.app_org(), and the runtime role is the
-- non-owner orevia_app without BYPASSRLS. Lock/volume impact is negligible
-- (six empty tables and one function). A later removal is a contract migration
-- with Forward-fix per docs/decisions/0002.

CREATE TABLE public.patient_access_account (
    organization_id  uuid NOT NULL REFERENCES public.organization(organization_id),
    id               uuid NOT NULL,
    subject          text NOT NULL,
    linked_chart_ids text[] NOT NULL DEFAULT '{}',
    fact_digest      text NOT NULL,
    state            text NOT NULL DEFAULT 'active'
                         CHECK (state IN ('active', 'locked')),
    failed_attempts  integer NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
    contact_digest   text,
    created_at       timestamptz NOT NULL,
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, subject)
);

CREATE TABLE public.patient_access_invitation (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL,
    code_hash       text NOT NULL,
    chart_id        uuid NOT NULL,
    fact_digest     text NOT NULL,
    state           text NOT NULL DEFAULT 'pending'
                        CHECK (state IN ('pending', 'redeemed')),
    failed_attempts integer NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
    expires_at      timestamptz NOT NULL,
    issued_by       text NOT NULL,
    issued_at       timestamptz NOT NULL,
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, code_hash),
    CHECK (expires_at > issued_at)
);

CREATE TABLE public.patient_access_token (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL,
    token_hash      text NOT NULL,
    subject         text NOT NULL,
    purpose         text NOT NULL,
    expires_at      timestamptz NOT NULL,
    used            boolean NOT NULL DEFAULT false,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, token_hash)
);

CREATE TABLE public.patient_access_support_case (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL,
    patient_id      text NOT NULL,
    kind            text NOT NULL
                        CHECK (kind IN ('identity_dispute', 'accessibility', 'record_access')),
    summary         text NOT NULL,
    state           text NOT NULL
                        CHECK (state IN ('open', 'in_review', 'resolved')),
    assignee        text,
    opened_at       timestamptz NOT NULL,
    PRIMARY KEY (organization_id, id)
);

CREATE TABLE public.patient_access_event (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL,
    subject         text NOT NULL,
    event_type      text NOT NULL,
    resource_id     text NOT NULL,
    outcome         text NOT NULL,
    detail          text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.patient_access_notification (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    subject         text NOT NULL,
    event_type      text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    PRIMARY KEY (organization_id, seq)
);

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'patient_access_account', 'patient_access_invitation', 'patient_access_token',
        'patient_access_support_case', 'patient_access_event', 'patient_access_notification'
    ]
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format(
            $p$CREATE POLICY tenant_isolation ON public.%I
                 USING (organization_id = public.app_org())
                 WITH CHECK (organization_id = public.app_org())$p$, t);
    END LOOP;
END $$;

-- The two ledgers are append-only for the owner as well: triggers bind the
-- migration role, which is not stopped by a GRANT-based approach.
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['patient_access_event', 'patient_access_notification']
    LOOP
        EXECUTE format(
            $d$CREATE TRIGGER %I_no_update_delete
                BEFORE UPDATE OR DELETE ON public.%I
                FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation()$d$, t, t);
        EXECUTE format(
            $d$CREATE TRIGGER %I_no_truncate
                BEFORE TRUNCATE ON public.%I
                FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation()$d$, t, t);
    END LOOP;
END $$;

-- Single use is atomic: only the caller that flips a pending, unexpired
-- invitation to redeemed wins, even when two requests race. The function runs
-- with invoker rights and forced RLS, so a caller bound to another tenant sees
-- zero rows and cannot consume this tenant's invitation.
CREATE OR REPLACE FUNCTION public.consume_patient_access_invitation(p_code_hash text)
RETURNS boolean LANGUAGE plpgsql SET search_path = pg_catalog
AS $$
DECLARE v_count integer;
BEGIN
    UPDATE public.patient_access_invitation
       SET state = 'redeemed'
     WHERE code_hash = p_code_hash
       AND state = 'pending'
       AND expires_at > now();
    GET DIAGNOSTICS v_count = ROW_COUNT;
    RETURN v_count = 1;
END $$;

REVOKE ALL ON FUNCTION public.consume_patient_access_invitation(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.consume_patient_access_invitation(text) TO orevia_app;

GRANT SELECT, INSERT, UPDATE ON public.patient_access_account,
                                public.patient_access_invitation,
                                public.patient_access_token,
                                public.patient_access_support_case TO orevia_app;
GRANT SELECT, INSERT ON public.patient_access_event,
                       public.patient_access_notification TO orevia_app;
REVOKE DELETE, TRUNCATE ON public.patient_access_account,
                          public.patient_access_invitation,
                          public.patient_access_token,
                          public.patient_access_support_case FROM orevia_app;
