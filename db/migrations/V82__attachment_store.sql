-- Requirement IDs: MSG-03, ARC-06, ARC-07
-- Change: expand
-- Durable message attachments, their verified connection grants and an
-- append-only fact ledger. Each table is tenant-owned and protected by forced
-- row-level security; a new table is not covered by V2's static table list, so
-- every policy, grant and trigger is declared here. The migration is additive.
--
-- Local identifiers are unique only inside a tenant, so every key includes
-- organization_id. A draft's uploader and conversation binding is immutable
-- for every role, including the migration owner; only its lifecycle columns
-- may advance. The fact ledger rejects mutation for every role as well.

CREATE TABLE public.attachment (
    organization_id   uuid NOT NULL REFERENCES public.organization(organization_id),
    id                uuid NOT NULL,
    version           integer NOT NULL CHECK (version > 0),
    uploader_subject  text NOT NULL,
    connection_id     text NOT NULL,
    unit_id           text NOT NULL,
    patient_id        text NOT NULL,
    file_name         text NOT NULL CHECK (length(file_name) BETWEEN 1 AND 200),
    file_type         text NOT NULL CHECK (file_type IN
                          ('application/pdf', 'image/jpeg', 'image/png')),
    size_bytes        bigint NOT NULL CHECK (size_bytes > 0),
    checksum          text NOT NULL,
    object_key        text NOT NULL,
    object_version    integer NOT NULL CHECK (object_version > 0),
    verdict           text NOT NULL CHECK (verdict IN ('pending', 'clean', 'failed')),
    state             text NOT NULL CHECK (state IN
                          ('quarantined', 'clean', 'published', 'failed', 'removed')),
    message_id        text,
    recipient_unit_id text,
    created_at        timestamptz NOT NULL,
    PRIMARY KEY (organization_id, id)
);

CREATE TABLE public.attachment_connection_grant (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    connection_id   text NOT NULL,
    unit_id         text NOT NULL,
    patient_id      text NOT NULL,
    active          boolean NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, connection_id)
);

CREATE TABLE public.attachment_event (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL,
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    attachment_id   text NOT NULL,
    event_type      text NOT NULL CHECK (event_type IN
                        ('uploaded', 'scan_clean', 'scan_failed', 'published',
                         'removed', 'downloaded', 'filed_to_chart', 'access_denied')),
    actor_subject   text NOT NULL,
    outcome         text NOT NULL,
    detail          text,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

-- A draft is bound to its uploader and conversation when it enters quarantine.
-- No role may rebind it to another uploader, connection, unit or patient, and
-- no role may move it backwards to a stale version. Lifecycle columns advance
-- only through the guarded upsert in the attachment store.
CREATE OR REPLACE FUNCTION public.attachment_binding_immutable()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog
AS $$
BEGIN
    IF NEW.organization_id IS DISTINCT FROM OLD.organization_id
       OR NEW.uploader_subject IS DISTINCT FROM OLD.uploader_subject
       OR NEW.connection_id IS DISTINCT FROM OLD.connection_id
       OR NEW.unit_id IS DISTINCT FROM OLD.unit_id
       OR NEW.patient_id IS DISTINCT FROM OLD.patient_id
       OR NEW.file_name IS DISTINCT FROM OLD.file_name
       OR NEW.file_type IS DISTINCT FROM OLD.file_type
       OR NEW.size_bytes IS DISTINCT FROM OLD.size_bytes
       OR NEW.checksum IS DISTINCT FROM OLD.checksum
       OR NEW.object_key IS DISTINCT FROM OLD.object_key
       OR NEW.object_version IS DISTINCT FROM OLD.object_version
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.version < OLD.version THEN
        RAISE EXCEPTION 'attachment binding is immutable (id=%)', OLD.id
            USING ERRCODE = '44000';
    END IF;
    RETURN NEW;
END $$;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['attachment', 'attachment_connection_grant', 'attachment_event']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format($p$CREATE POLICY tenant_isolation ON public.%I
             USING (organization_id = public.app_org())
             WITH CHECK (organization_id = public.app_org())$p$, t);
    END LOOP;

    EXECUTE $b$CREATE TRIGGER attachment_binding_guard
        BEFORE UPDATE ON public.attachment
        FOR EACH ROW EXECUTE FUNCTION public.attachment_binding_immutable()$b$;

    -- Append-only for every role, including the migration owner; a GRANT
    -- alone would not cover the owner.
    EXECUTE $d$CREATE TRIGGER attachment_event_no_update_delete
        BEFORE UPDATE OR DELETE ON public.attachment_event
        FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
    EXECUTE $d$CREATE TRIGGER attachment_event_no_truncate
        BEFORE TRUNCATE ON public.attachment_event
        FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
END $$;

CREATE INDEX attachment_unit_idx ON public.attachment (organization_id, unit_id, created_at DESC);
CREATE INDEX attachment_connection_idx ON public.attachment (organization_id, connection_id);
CREATE INDEX attachment_event_attachment_idx
    ON public.attachment_event (organization_id, attachment_id, seq);

-- The runtime role advances attachment state and seeds/sweeps synthetic grants.
-- Deletion and fact mutation are never granted; soft REMOVED is a state, not a
-- row delete. The append-only triggers above cover the migrate owner too.
GRANT SELECT, INSERT, UPDATE ON public.attachment TO orevia_app;
GRANT SELECT, INSERT, UPDATE ON public.attachment_connection_grant TO orevia_app;
GRANT SELECT, INSERT ON public.attachment_event TO orevia_app;
REVOKE DELETE, TRUNCATE ON public.attachment FROM orevia_app;
REVOKE DELETE, TRUNCATE ON public.attachment_connection_grant FROM orevia_app;
REVOKE UPDATE, DELETE, TRUNCATE ON public.attachment_event FROM orevia_app;
