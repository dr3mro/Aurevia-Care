-- Requirement IDs: ARC-01, ARC-02, OPS-02
-- Change: expand
-- Durable MSG-07 messaging governance facts. Each aggregate the governance
-- store owns gets one tenant-owned table: append-only audit and fact ledgers,
-- approved retention policy and record-access policy, tracked resources,
-- retention duties, legal holds, connection references, chart provenance links,
-- expiring exports and copy requests. Every table carries an organization_id,
-- a server creation instant and forced row-level security; a new table is not
-- covered by V2's static table list, so every policy, grant and trigger is
-- declared here. The migration is additive only.
--
-- Local identifiers are unique only inside a tenant, so every primary key and
-- every business key includes organization_id. Identical local identifiers in
-- two tenants therefore remain isolated. Append-only facts receive no UPDATE,
-- DELETE or TRUNCATE grant and are protected by reject-mutation triggers for
-- every role, including the migration owner. Current-state configuration uses
-- ON CONFLICT DO UPDATE and therefore needs the UPDATE grant.

CREATE TABLE public.messaging_audit_event (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL,
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    subject         text NOT NULL,
    purpose         text,
    action          text NOT NULL,
    resource_id     text NOT NULL,
    unit_id         text,
    correlation_id  text,
    outcome         text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

CREATE TABLE public.messaging_retention_policy (
