DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'messaging_audit_event', 'messaging_retention_policy', 'messaging_resource',
        'messaging_retention_duty', 'messaging_legal_hold', 'messaging_record_access_policy',
        'messaging_connection', 'messaging_provenance_link', 'messaging_export',
        'messaging_copy_request', 'messaging_revocation_effect'
    ]
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format($p$CREATE POLICY tenant_isolation ON public.%I
             USING (organization_id = public.app_org())
             WITH CHECK (organization_id = public.app_org())$p$, t);
    END LOOP;

    -- Append-only facts are immutable for every role, including the owner;
    -- a GRANT alone would not cover the migration owner.
    FOREACH t IN ARRAY ARRAY[
        'messaging_audit_event', 'messaging_provenance_link',
        'messaging_copy_request', 'messaging_revocation_effect', 'messaging_export'
    ]
    LOOP
        EXECUTE format($d$CREATE TRIGGER %I_no_update_delete
            BEFORE UPDATE OR DELETE ON public.%I
            FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation()$d$, t, t);
        EXECUTE format($d$CREATE TRIGGER %I_no_truncate
            BEFORE TRUNCATE ON public.%I
            FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation()$d$, t, t);
    END LOOP;
END $$;

