-- The actor is always the authenticated subject, never caller-supplied.
CREATE OR REPLACE FUNCTION public.set_identity_actor()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog
AS $$
BEGIN
    NEW.created_by := NULLIF(current_setting('app.actor', true), '');
    IF NEW.created_by IS NULL THEN
        RAISE EXCEPTION 'identity command requires an authenticated actor'
            USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION public.set_link_actor()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog
AS $$
BEGIN
    NEW.created_by := NULLIF(current_setting('app.actor', true), '');
    IF NEW.created_by IS NULL THEN
        RAISE EXCEPTION 'identity command requires an authenticated actor'
            USING ERRCODE = '42501';
    END IF;
    NEW.verified_by := NEW.created_by;
    RETURN NEW;
END $$;
CREATE TRIGGER patient_account_created_by_actor
    BEFORE INSERT ON public.patient_account
    FOR EACH ROW EXECUTE FUNCTION public.set_identity_actor();
CREATE TRIGGER account_invitation_created_by_actor
    BEFORE INSERT ON public.account_invitation
    FOR EACH ROW EXECUTE FUNCTION public.set_identity_actor();
CREATE TRIGGER account_chart_link_created_by_actor
    BEFORE INSERT ON public.account_chart_link
    FOR EACH ROW EXECUTE FUNCTION public.set_link_actor();

-- One current link per (org, account, chart): the highest database-owned seq.
CREATE OR REPLACE FUNCTION public.current_chart_links()
RETURNS TABLE (organization_id uuid, account_id uuid, account_subject text, chart_id uuid,
               event text, method text, reason text, verified_by text,
               occurred_at timestamptz, seq bigint)
LANGUAGE sql STABLE SET search_path = pg_catalog
AS $$
    SELECT DISTINCT ON (l.organization_id, l.account_id, l.chart_id)
           l.organization_id, l.account_id, a.subject, l.chart_id, l.event, l.method,
           l.reason, l.verified_by, l.occurred_at, l.seq
      FROM public.account_chart_link l
      JOIN public.patient_account a
        ON a.organization_id = l.organization_id AND a.id = l.account_id
     ORDER BY l.organization_id, l.account_id, l.chart_id, l.seq DESC
$$;

-- Access is a live fold over link events; no session cache or stale token can
-- keep access after an unlink. Forced RLS confines the function to the tenant.
CREATE OR REPLACE FUNCTION public.has_chart_access(p_subject text, p_chart_id uuid)
RETURNS boolean LANGUAGE sql STABLE SET search_path = pg_catalog
AS $$
    SELECT coalesce(bool_or(event = 'linked'), false)
      FROM public.current_chart_links()
     WHERE account_subject = p_subject AND chart_id = p_chart_id
$$;

-- Single use is atomic: only the caller that flips used_at from NULL wins.
-- Expiry is enforced by the database clock, not by a trustable client value.
CREATE OR REPLACE FUNCTION public.consume_invitation(p_id uuid)
RETURNS boolean LANGUAGE plpgsql SET search_path = pg_catalog
AS $$
DECLARE v_count integer;
BEGIN
    UPDATE public.account_invitation
       SET used_at = now()
     WHERE id = p_id AND used_at IS NULL AND expires_at > now();
    GET DIAGNOSTICS v_count = ROW_COUNT;
    RETURN v_count = 1;
END $$;

