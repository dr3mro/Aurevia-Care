-- Requirement IDs: IAM-05, ARC-01, ARC-02, OPS-02
-- Change: expand
-- Verified patient accounts, single-use expiring invitations and append-only
-- account-to-chart links. Access is derived from the latest link event, so an
-- unlink ends future account access on the next protected request. A link is
-- keyed to the immutable patient chart id, never to mutable contact data.

CREATE TABLE public.patient_account (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    subject         text NOT NULL,
    display_name    text NOT NULL,
    created_by      text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, subject)
);

CREATE TABLE public.account_invitation (
    organization_id uuid NOT NULL,
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    account_id      uuid NOT NULL,
    chart_id        uuid NOT NULL,
    token_hash      text NOT NULL,
    purpose         text NOT NULL CHECK (purpose IN ('ENROLL', 'LINK', 'REVERIFY')),
    expires_at      timestamptz NOT NULL,
    used_at         timestamptz,
    created_by      text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, token_hash),
    CHECK (expires_at > created_at),
    FOREIGN KEY (organization_id, account_id)
        REFERENCES public.patient_account(organization_id, id),
    FOREIGN KEY (organization_id, chart_id)
        REFERENCES public.patient_record(organization_id, id)
);

CREATE TABLE public.account_chart_link (
    organization_id uuid NOT NULL,
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    account_id      uuid NOT NULL,
    chart_id        uuid NOT NULL,
    event           text NOT NULL CHECK (event IN ('linked', 'unlinked')),
    method          text NOT NULL,
    reason          text,
    verified_by     text NOT NULL,
    occurred_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq),
    FOREIGN KEY (organization_id, account_id)
        REFERENCES public.patient_account(organization_id, id),
    FOREIGN KEY (organization_id, chart_id)
        REFERENCES public.patient_record(organization_id, id)
);

