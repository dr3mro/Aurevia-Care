-- Requirement IDs: CLN-04, ARC-02, OPS-02
-- Change: expand
--
-- Durable store for versioned clinical note templates (CLN-04). Four tenant-owned
-- tables plus a per-family version counter: site field dictionaries, immutable
-- published template versions, saved note revisions and an append-only audit
-- trail. Each version keeps its complete field definitions as JSON, and each
-- saved note keeps the field meanings and dictionary entries it was saved with,
-- so a later dictionary change cannot rewrite the meaning of an old note.
--
-- Every table is tenant owned with ENABLE + FORCE RLS, a policy using app_org()
-- with WITH CHECK, and explicit grants. New tables are not covered by V2's
-- static policy list, so all of it is declared here. Additive only: no backfill,
-- no destructive DDL and no dependency on application data.

CREATE TABLE public.template_field_dictionary (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    dictionary_key  text NOT NULL CHECK (btrim(dictionary_key) <> ''),
    entries         jsonb NOT NULL CHECK (jsonb_typeof(entries) = 'array'),
    approved        boolean NOT NULL DEFAULT false,
    approved_by     text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, dictionary_key)
);

-- Version numbers are tenant and family local. The counter is allocated by one
-- atomic upsert, so two concurrent definers cannot claim the same version.
CREATE TABLE public.template_version_sequence (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    kind            text NOT NULL CHECK (kind IN
        ('SOAP', 'OPERATIVE', 'OBGYN', 'PERINATAL', 'PEDIATRIC_DEVELOPMENT')),
    next_version    integer NOT NULL DEFAULT 2 CHECK (next_version > 1),
    PRIMARY KEY (organization_id, kind)
);

CREATE TABLE public.template_version (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    kind            text NOT NULL CHECK (kind IN
        ('SOAP', 'OPERATIVE', 'OBGYN', 'PERINATAL', 'PEDIATRIC_DEVELOPMENT')),
    version         integer NOT NULL CHECK (version > 0),
    approved        boolean NOT NULL DEFAULT false,
    fields          jsonb NOT NULL CHECK (jsonb_typeof(fields) = 'array'),
    approved_by     text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, kind, version)
);

-- field_meanings is the exact version field set at save time; dictionaries is a
-- key-to-entries snapshot of the referenced dictionaries at save time. Both are
-- application-written JSON facts, never re-derived on read.
CREATE TABLE public.template_note_revision (
    organization_id  uuid NOT NULL REFERENCES public.organization(organization_id),
    note_id          text NOT NULL CHECK (btrim(note_id) <> ''),
    kind             text NOT NULL CHECK (kind IN
        ('SOAP', 'OPERATIVE', 'OBGYN', 'PERINATAL', 'PEDIATRIC_DEVELOPMENT')),
    template_version integer NOT NULL CHECK (template_version > 0),
    patient_ref      text NOT NULL,
    author           text NOT NULL,
    values           jsonb NOT NULL CHECK (jsonb_typeof(values) = 'array'),
    field_meanings   jsonb NOT NULL CHECK (jsonb_typeof(field_meanings) = 'array'),
    dictionaries     jsonb NOT NULL CHECK (jsonb_typeof(dictionaries) = 'object'),
    created_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, note_id)
);

CREATE TABLE public.template_audit_event (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    event_id        bigint GENERATED BY DEFAULT AS IDENTITY,
    actor_subject   text NOT NULL,
    action          text NOT NULL,
    resource_type   text NOT NULL,
    resource_id     text NOT NULL,
    outcome         text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, event_id)
);

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'template_field_dictionary', 'template_version_sequence', 'template_version',
        'template_note_revision', 'template_audit_event']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format($p$CREATE POLICY tenant_isolation ON public.%I
             USING (organization_id = public.app_org())
             WITH CHECK (organization_id = public.app_org())$p$, t);
    END LOOP;
END $$;

-- Governance publication freezes a version's meaning: no role, including the
-- migration owner, may rewrite or remove a published version or its history.
CREATE OR REPLACE FUNCTION public.guard_published_template_version()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'published template versions cannot be deleted'
            USING ERRCODE = '23514';
    END IF;
    IF OLD.approved THEN
        RAISE EXCEPTION 'a published template version is immutable'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER template_version_published_immutable
    BEFORE UPDATE OR DELETE ON public.template_version
    FOR EACH ROW EXECUTE FUNCTION public.guard_published_template_version();

-- Saved note revisions and audit facts are append-only for every role.
CREATE TRIGGER template_note_revision_no_update_delete
    BEFORE UPDATE OR DELETE ON public.template_note_revision
    FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation();
CREATE TRIGGER template_note_revision_no_truncate
    BEFORE TRUNCATE ON public.template_note_revision
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation();
CREATE TRIGGER template_audit_event_no_update_delete
    BEFORE UPDATE OR DELETE ON public.template_audit_event
    FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation();
CREATE TRIGGER template_audit_event_no_truncate
    BEFORE TRUNCATE ON public.template_audit_event
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation();

REVOKE ALL ON FUNCTION public.guard_published_template_version() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.guard_published_template_version() TO orevia_app;

GRANT SELECT, INSERT, UPDATE ON public.template_field_dictionary TO orevia_app;
GRANT SELECT, INSERT, UPDATE ON public.template_version_sequence TO orevia_app;
GRANT SELECT, INSERT, UPDATE ON public.template_version TO orevia_app;
GRANT SELECT, INSERT ON public.template_note_revision TO orevia_app;
GRANT SELECT, INSERT ON public.template_audit_event TO orevia_app;
REVOKE DELETE, TRUNCATE ON public.template_field_dictionary FROM orevia_app;
REVOKE DELETE, TRUNCATE ON public.template_version_sequence FROM orevia_app;
REVOKE DELETE, TRUNCATE ON public.template_version FROM orevia_app;
REVOKE UPDATE, DELETE, TRUNCATE ON public.template_note_revision FROM orevia_app;
REVOKE UPDATE, DELETE, TRUNCATE ON public.template_audit_event FROM orevia_app;
