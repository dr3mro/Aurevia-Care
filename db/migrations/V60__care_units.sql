-- Requirement IDs: MSG-01, MSG-07, ARC-01, ARC-02, OPS-02
-- Change: expand
-- Durable care-unit directory, verified relationships, patient-unit connections
-- and non-sensitive messaging authorization facts. Each table is tenant-owned,
-- carries a creation instant and is protected by forced row-level security; a
-- new table is not covered by V2's static table list, so every policy, grant and
-- trigger is declared here. The migration is additive only.
--
-- Local identifiers are unique only inside a tenant, so every primary key and
-- the connection business key include organization_id. Identical local ids in
-- two tenants therefore remain isolated. Append-only facts reject mutation for
-- every role, including the migration owner; state-bearing rows use a narrow
-- UPDATE grant so only the intended transition can be written by the app role.

CREATE TABLE public.care_unit (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    facility_id     uuid,
    name            text NOT NULL,
    topics          text[] NOT NULL DEFAULT '{}',
    active          boolean NOT NULL,
    unit_key        text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id)
);

CREATE TABLE public.eligible_relationship (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    patient_id      uuid NOT NULL,
    unit_id         uuid NOT NULL,
    context         text NOT NULL CHECK (context IN
        ('care_relationship', 'order', 'referral', 'prescription', 'invitation')),
    reference       text NOT NULL,
    active          boolean NOT NULL,
    consumed        boolean NOT NULL DEFAULT false,
    expires_at      timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id)
);

CREATE TABLE public.patient_unit_connection (
    organization_id   uuid NOT NULL REFERENCES public.organization(organization_id),
    id                uuid NOT NULL DEFAULT gen_random_uuid(),
    patient_id        uuid NOT NULL,
    unit_id           uuid NOT NULL,
    context           text NOT NULL CHECK (context IN
        ('care_relationship', 'order', 'referral', 'prescription', 'invitation')),
    context_reference text NOT NULL,
    relationship_id   uuid NOT NULL,
    state             text NOT NULL CHECK (state IN ('active', 'revoked')),
    verified_by       text NOT NULL,
    verified_at       timestamptz NOT NULL,
    revoked_at        timestamptz,
    created_at        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    -- One connection per verified source reference: a retry returns the row
    -- that already won instead of opening a parallel conversation.
    UNIQUE (organization_id, patient_id, unit_id, context_reference)
);

CREATE TABLE public.messaging_audit (
    organization_id uuid NOT NULL REFERENCES public.organization(organization_id),
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    seq             bigint GENERATED BY DEFAULT AS IDENTITY,
    subject         text NOT NULL,
    action          text NOT NULL,
    resource_id     text NOT NULL,
    outcome         text NOT NULL,
    occurred_at     timestamptz NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, id),
    UNIQUE (organization_id, seq)
);

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['care_unit', 'eligible_relationship',
                             'patient_unit_connection', 'messaging_audit']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format($p$CREATE POLICY tenant_isolation ON public.%I
             USING (organization_id = public.app_org())
             WITH CHECK (organization_id = public.app_org())$p$, t);
    END LOOP;

    -- The audit trail is an append-only fact ledger for every role.
    EXECUTE $d$CREATE TRIGGER messaging_audit_no_update_delete
        BEFORE UPDATE OR DELETE ON public.messaging_audit
        FOR EACH ROW EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
    EXECUTE $d$CREATE TRIGGER messaging_audit_no_truncate
        BEFORE TRUNCATE ON public.messaging_audit
        FOR EACH STATEMENT EXECUTE FUNCTION public.reject_immutable_mutation()$d$;
END $$;

-- Directory and relationship rows are immutable; consumption and revocation are
-- the only state moves and may flip one boolean or stamp one transition.
GRANT SELECT, INSERT ON public.care_unit TO aurevia_app;
GRANT SELECT, INSERT, UPDATE ON public.eligible_relationship TO aurevia_app;
GRANT SELECT, INSERT, UPDATE ON public.patient_unit_connection TO aurevia_app;
GRANT SELECT, INSERT ON public.messaging_audit TO aurevia_app;
REVOKE UPDATE, DELETE, TRUNCATE ON public.care_unit FROM aurevia_app;
REVOKE DELETE, TRUNCATE ON public.eligible_relationship FROM aurevia_app;
REVOKE DELETE, TRUNCATE ON public.patient_unit_connection FROM aurevia_app;
REVOKE UPDATE, DELETE, TRUNCATE ON public.messaging_audit FROM aurevia_app;
